func TestInitAppleRuntimeWritesTheScriptsAndTheAgent(t *testing.T) {
	opts := testOptions(t)
	opts.Runtime = RuntimeApple
	res, err := Init(opts)
	if err != nil {
		t.Fatal(err)
	}
	if res.Runtime != RuntimeApple || res.ComposeFile != "" || res.ServerURL != "https://localhost:8443" || res.TLS != TLSGenerated {
		t.Errorf("result = %+v", res)
	}
	up, down := filepath.Join(opts.Dir, UpScript), filepath.Join(opts.Dir, DownScript)
	if res.Up != "bash "+up || res.Down != "bash "+down || res.Logs != "container logs clued-server" || !strings.Contains(res.Health, "--cacert "+res.CAFile) {
		t.Errorf("up = %q, down = %q, logs = %q, health = %q", res.Up, res.Down, res.Logs, res.Health)
	}
	if len(res.Notes) != 1 || !strings.Contains(res.Notes[0], LaunchdLabel) || !strings.Contains(res.Notes[0], "root") {
		t.Errorf("notes = %v", res.Notes)
	}
	for _, f := range []string{UpScript, DownScript, LaunchdPlist, NginxConf, ConfigFile, StackFile, CAFile, CertFile, KeyFile, TokensFile} {
		if _, err := os.Stat(filepath.Join(opts.Dir, f)); err != nil {
			t.Errorf("%s missing: %v", f, err)
		}
	}
	if _, err := os.Stat(filepath.Join(opts.Dir, ComposeFile)); err == nil {
		t.Error("the Apple runtime wrote a compose file")
	}
	for _, f := range []string{UpScript, DownScript} {
		if m := mode(t, filepath.Join(opts.Dir, f)); m != 0o755 {
			t.Errorf("%s mode = %o, want 0755", f, m)
		}
	}

	script, _ := os.ReadFile(up)
	for _, want := range []string{
		"#!/usr/bin/env bash\n", "set -euo pipefail\n", "DIR=" + shellQuote(opts.Dir) + "\n", "PROXY=nginx\n", "PORT=8443\n",
		"SERVER_IMAGE=ghcr.io/robbiebyrd/clued-server:v9.9.9\n", "NGINX_IMAGE=" + DefaultNginxImage + "\n", "MONGO_IMAGE=" + DefaultMongoImage + "\n",
		"CONTAINERS=(clued-mongo clued-server clued-nginx)\n", "container system start", "container volume create \"$VOLUME\"",
		`--publish "0.0.0.0:${PORT}:443"`, "--user 0:0", `--mount "type=bind,source=${DIR},target=/etc/clued,readonly"`,
		"CLUED_MONGO_URL=mongodb://${MONGO_IP}:27017", "s#clued-server:8443#${SERVER_IP}:8443#g", "launchctl load -w",
		"generated by 'mind-palace server\n# init' on 2026-10-13",
	} {
		if !strings.Contains(string(script), want) {
			t.Errorf("up.sh lacks %q:\n%s", want, script)
		}
	}
	if strings.Contains(string(script), "${CLUED_") {
		t.Error("up.sh reads CLUED_* overrides; the values are literal")
	}
	plist, _ := os.ReadFile(filepath.Join(opts.Dir, LaunchdPlist))
	for _, want := range []string{"<string>" + LaunchdLabel + "</string>", "<string>/bin/bash</string>", "<string>" + up + "</string>", "<key>RunAtLoad</key>", filepath.Join(opts.Dir, "launchd/up.log")} {
		if !strings.Contains(string(plist), want) {
			t.Errorf("plist lacks %q:\n%s", want, plist)
		}
	}
	stackDoc, _ := os.ReadFile(filepath.Join(opts.Dir, StackFile))
	if !strings.Contains(string(stackDoc), `"runtime": "apple"`) || !strings.Contains(string(stackDoc), `"up": "bash `+up+`"`) {
		t.Errorf("stack.json:\n%s", stackDoc)
	}
	checkBash(t, up, down)

	// --proxy none publishes the server on loopback and starts no nginx.
	opts.Proxy = ProxyNone
	opts.Port = 9000
	opts.NoToken = true
	res, err = Init(opts)
	if err != nil {
		t.Fatal(err)
	}
	script, _ = os.ReadFile(up)
	if !strings.Contains(string(script), "CONTAINERS=(clued-mongo clued-server)\n") || !strings.Contains(string(script), `--publish "127.0.0.1:${PORT}:8443"`) || !strings.Contains(string(script), "PORT=9000\n") {
		t.Errorf("up.sh with --proxy none:\n%s", script)
	}
	if res.ServerURL != "http://127.0.0.1:9000" || res.Health != "curl http://127.0.0.1:9000/health" {
		t.Errorf("result = %+v", res)
	}
	if _, err := os.Stat(filepath.Join(opts.Dir, NginxConf)); err == nil {
		t.Error("nginx.conf written without a front-end")
	}

	// Switching back to compose removes the scripts and the agent.
	opts.Runtime = RuntimeCompose
	opts.Proxy = ProxyNginx
	res, err = Init(opts)
	if err != nil {
		t.Fatal(err)
	}
	if res.Runtime != RuntimeCompose || res.ComposeFile == "" {
		t.Errorf("result = %+v", res)
	}
	for _, f := range []string{UpScript, DownScript, LaunchdPlist} {
		if _, err := os.Stat(filepath.Join(opts.Dir, f)); err == nil {
			t.Errorf("%s left behind after switching to compose", f)
		}
	}
	if _, err := os.Stat(filepath.Join(opts.Dir, ComposeFile)); err != nil {
		t.Errorf("compose file missing after switching back: %v", err)
	}
}

// fakeContainer puts a `container` on PATH that logs its arguments, one
// call per line, answers `inspect` with a running container whose address
// depends on its name, and lists the data volume.
func fakeContainer(t *testing.T) (binDir, logFile string) {
	t.Helper()
	binDir = t.TempDir()
	logFile = filepath.Join(t.TempDir(), "container.log")
	body := `#!/bin/sh
echo "$*" >> ` + logFile + `
case "$1" in
  inspect)
    case "$2" in
      clued-mongo) n=3 ;;
      clued-server) n=4 ;;
      *) n=5 ;;
    esac
    echo '[{"status":{"state":"running","networks":[{"ipv4Address":"192.168.64.'$n'/24","network":"default"}]}}]'
    ;;
  volume)
    [ "$2" = list ] && echo clued_mongo_data
    ;;
esac
exit 0
`
	if err := os.WriteFile(filepath.Join(binDir, "container"), []byte(body), 0o755); err != nil {
		t.Fatal(err)
	}
	return binDir, logFile
}

func TestUpAndDownScriptsDriveTheContainerCLI(t *testing.T) {
	bash, err := exec.LookPath("bash")
	if err != nil {
		t.Skip("bash not installed")
	}
	opts := testOptions(t)
	opts.Runtime = RuntimeApple
	res, err := Init(opts)
	if err != nil {
		t.Fatal(err)
	}
	binDir, logFile := fakeContainer(t)
	home := t.TempDir()
	run := func(script string, args ...string) (string, error) {
		cmd := exec.Command(bash, append([]string{filepath.Join(opts.Dir, script)}, args...)...)
		cmd.Env = []string{"HOME=" + home, "PATH=" + binDir + ":" + os.Getenv("PATH")}
		out, err := cmd.CombinedOutput()
		return string(out), err
	}

	out, err := run(UpScript, "--recreate")
	if err != nil {
		t.Fatalf("up.sh --recreate: %v\n%s", err, out)
	}
	if !strings.Contains(out, "clued: server stack started") {
		t.Errorf("up.sh output:\n%s", out)
	}
	calls, _ := os.ReadFile(logFile)
	for _, want := range []string{
		"system status\n",
		"delete --force clued-mongo clued-server clued-nginx\n",
		"volume create clued_mongo_data\n",
		"run --detach --name clued-mongo --volume clued_mongo_data:/data/db " + DefaultMongoImage + "\n",
		"exec clued-mongo mongosh --port 27017 --quiet --eval db.runCommand(\"ping\").ok\n",
		"run --detach --name clued-server --user 0:0 --mount type=bind,source=" + opts.Dir + ",target=/etc/clued,readonly --env CLUED_SERVER_ADDR=0.0.0.0:8443 --env CLUED_SERVER_TOKENS=/etc/clued/tokens.json --env MIND_PALACE_CONFIG=/etc/clued/run/mind-palace.config.yaml --env CLUED_MONGO_URL=mongodb://192.168.64.3:27017 --env CLUED_DB_NAME=claude_sessions --env CLUED_SERVER_BEHIND_PROXY=true ghcr.io/robbiebyrd/clued-server:v9.9.9\n",
		"run --detach --name clued-nginx --publish 0.0.0.0:8443:443 --mount type=bind,source=" + opts.Dir + "/run/nginx,target=/etc/nginx/conf.d,readonly --mount type=bind,source=" + opts.Dir + "/tls,target=/etc/nginx/tls,readonly " + DefaultNginxImage + "\n",
	} {
		if !strings.Contains(string(calls), want) {
			t.Errorf("container calls lack %q:\n%s", want, calls)
		}
	}
	if strings.Contains(string(calls), "--publish 127.0.0.1") {
		t.Errorf("with nginx the server must not be published itself:\n%s", calls)
	}
	cfg, _ := os.ReadFile(filepath.Join(opts.Dir, "run", ConfigFile))
	if !strings.Contains(string(cfg), "uri: mongodb://192.168.64.3:27017") {
		t.Errorf("run/%s not rendered with the MongoDB address:\n%s", ConfigFile, cfg)
	}
	nginx, _ := os.ReadFile(filepath.Join(opts.Dir, "run", NginxConf))
	if !strings.Contains(string(nginx), "proxy_pass http://192.168.64.4:8443;") || strings.Contains(string(nginx), "clued-server:8443") {
		t.Errorf("run/%s not rendered with the server address:\n%s", NginxConf, nginx)
	}
	if _, err := os.Stat(filepath.Join(home, "Library/LaunchAgents")); err == nil {
		t.Error("the agent was installed without a LaunchAgents directory")
	}

	// With the containers running, a plain start changes nothing.
	os.Remove(logFile)
	out, err = run(UpScript)
	if err != nil || !strings.Contains(out, "already running") {
		t.Fatalf("up.sh: %v\n%s", err, out)
	}
	calls, _ = os.ReadFile(logFile)
	if strings.Contains(string(calls), "run ") || strings.Contains(string(calls), "delete") {
		t.Errorf("a running stack was touched:\n%s", calls)
	}

	// down.sh removes the containers and keeps the data; --volumes deletes it.
	os.Remove(logFile)
	out, err = run(DownScript)
	if err != nil || !strings.Contains(out, "is kept") {
		t.Fatalf("down.sh: %v\n%s", err, out)
	}
	calls, _ = os.ReadFile(logFile)
	if !strings.Contains(string(calls), "delete --force clued-nginx clued-server clued-mongo\n") || strings.Contains(string(calls), "volume delete") {
		t.Errorf("down.sh calls:\n%s", calls)
	}
	if _, err := os.Stat(filepath.Join(opts.Dir, "run")); !os.IsNotExist(err) {
		t.Error("down.sh left run/ behind")
	}
	os.Remove(logFile)
	out, err = run(DownScript, "--volumes")
	if err != nil || !strings.Contains(out, "data deleted") {
		t.Fatalf("down.sh --volumes: %v\n%s", err, out)
	}
	calls, _ = os.ReadFile(logFile)
	if !strings.Contains(string(calls), "volume delete clued_mongo_data\n") {
		t.Errorf("down.sh --volumes calls:\n%s", calls)
	}
	if out, err := run(DownScript, "--bogus"); err == nil || !strings.Contains(out, "usage: down.sh") {
		t.Errorf("down.sh --bogus: %v\n%s", err, out)
	}
	_ = res
}

func TestDetectRuntime(t *testing.T) {
	have := func(names ...string) func(string) (string, error) {
		return func(name string) (string, error) {
			for _, n := range names {
				if n == name {
					return "/usr/local/bin/" + name, nil
				}
			}
			return "", errors.New("not found")
		}
	}
	for _, tc := range []struct {
		goos string
		have []string
		want string
	}{
		{"darwin", []string{"docker", "container"}, RuntimeCompose},
		{"darwin", []string{"docker"}, RuntimeCompose},
		{"darwin", []string{"container"}, RuntimeApple},
		{"darwin", nil, RuntimeCompose},
		{"linux", []string{"container"}, RuntimeCompose},
		{"linux", []string{"docker"}, RuntimeCompose},
	} {
		if got := DetectRuntime(tc.goos, have(tc.have...)); got != tc.want {
			t.Errorf("DetectRuntime(%s, %v) = %q, want %q", tc.goos, tc.have, got, tc.want)
		}
	}
}

// checkBash asks bash to parse the scripts when it is installed.
func checkBash(t *testing.T, scripts ...string) {
	t.Helper()
	bash, err := exec.LookPath("bash")
	if err != nil {
		t.Log("bash not installed; scripts not parsed")
		return
	}
	for _, s := range scripts {
		if out, err := exec.Command(bash, "-n", s).CombinedOutput(); err != nil {
			t.Errorf("bash -n %s: %v\n%s", s, err, out)
		}
	}
}
