func contains(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}

// validateCompose asks the Docker Compose CLI to parse the file when it is
// installed; parsing needs no daemon.
func validateCompose(t *testing.T, path string) {
	t.Helper()
	docker, err := exec.LookPath("docker")
	if err != nil {
		t.Log("docker not installed; compose file not validated")
		return
	}
	cmd := exec.Command(docker, "compose", "-f", path, "config", "--quiet")
	cmd.Env = append(os.Environ(), "DOCKER_HOST=unix:///nonexistent/docker.sock")
	if out, err := cmd.CombinedOutput(); err != nil {
		if strings.Contains(string(out), "is not a docker command") || strings.Contains(string(out), "unknown command") {
			t.Logf("docker compose not installed; compose file not validated: %s", out)
			return
		}
		t.Errorf("docker compose config rejects %s: %v\n%s", path, err, out)
	}
}
