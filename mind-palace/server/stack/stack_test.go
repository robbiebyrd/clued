func testOptions(t *testing.T) Options {
	t.Helper()
	return Options{
		Dir:         filepath.Join(t.TempDir(), "stack"),
		Hostname:    "Laptop.Example",
		Hosts:       []string{"clued.example.test", "10.0.0.5"},
		ServerImage: "ghcr.io/robbiebyrd/clued-server:v9.9.9",
		UID:         1234,
		GID:         5678,
		Now:         func() time.Time { return time.Date(2026, 10, 13, 12, 0, 0, 0, time.UTC) },
	}
}

func readPEMCert(t *testing.T, path string) *x509.Certificate {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	block, _ := pem.Decode(raw)
	if block == nil || block.Type != "CERTIFICATE" {
		t.Fatalf("%s holds no certificate", path)
	}
	cert, err := x509.ParseCertificate(block.Bytes)
	if err != nil {
		t.Fatal(err)
	}
	return cert
}

func mode(t *testing.T, path string) os.FileMode {
	t.Helper()
	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	return info.Mode().Perm()
}

func TestInitWritesTheStack(t *testing.T) {
	opts := testOptions(t)
	res, err := Init(opts)
	if err != nil {
		t.Fatal(err)
	}
	if res.Dir != opts.Dir || res.Runtime != RuntimeCompose || res.ComposeFile != filepath.Join(opts.Dir, ComposeFile) || res.Proxy != ProxyNginx || res.Port != DefaultPort {
		t.Errorf("result = %+v", res)
	}
	if res.ServerURL != "https://localhost:8443" || res.CAFile != filepath.Join(opts.Dir, CAFile) || res.TLS != TLSGenerated {
		t.Errorf("url/ca/tls = %q %q %q", res.ServerURL, res.CAFile, res.TLS)
	}
	if res.Up != "docker compose -f "+res.ComposeFile+" up -d" || res.Down != "docker compose -f "+res.ComposeFile+" down" || res.Logs != "docker compose -f "+res.ComposeFile+" logs clued-server nginx" || !strings.Contains(res.Health, "--cacert "+res.CAFile) {
		t.Errorf("up = %q, down = %q, logs = %q, health = %q", res.Up, res.Down, res.Logs, res.Health)
	}
	for _, f := range []string{ComposeFile, ConfigFile, NginxConf, StackFile, CAFile, CAKeyFile, CertFile, KeyFile, TokensFile} {
		if _, err := os.Stat(filepath.Join(opts.Dir, f)); err != nil {
			t.Errorf("%s missing: %v", f, err)
		}
	}
	for _, f := range []string{CAKeyFile, KeyFile, TokensFile} {
		if m := mode(t, filepath.Join(opts.Dir, f)); m != 0o600 {
			t.Errorf("%s mode = %o, want 0600", f, m)
		}
	}

	// The certificate chain verifies for every host and the CA is private.
	ca := readPEMCert(t, filepath.Join(opts.Dir, CAFile))
	leaf := readPEMCert(t, filepath.Join(opts.Dir, CertFile))
	if !ca.IsCA || strings.Contains(ca.Subject.CommonName, "Laptop") || !strings.Contains(ca.Subject.CommonName, "laptop.example") {
		t.Errorf("CA = %+v", ca.Subject)
	}
	pool := x509.NewCertPool()
	pool.AddCert(ca)
	for _, host := range []string{"localhost", "laptop.example", "clued.example.test", "127.0.0.1", "::1", "10.0.0.5"} {
		if _, err := leaf.Verify(x509.VerifyOptions{Roots: pool, DNSName: host, CurrentTime: opts.Now()}); err != nil {
			t.Errorf("certificate does not cover %s: %v", host, err)
		}
	}
	if _, err := leaf.Verify(x509.VerifyOptions{Roots: pool, DNSName: "other.example", CurrentTime: opts.Now()}); err == nil {
		t.Error("certificate covers a name it was not asked for")
	}
	if _, err := tls.LoadX509KeyPair(filepath.Join(opts.Dir, CertFile), filepath.Join(opts.Dir, KeyFile)); err != nil {
		t.Errorf("cert.pem and key.pem do not pair: %v", err)
	}
	want := []string{"localhost", "127.0.0.1", "::1", "laptop.example", "clued.example.test", "10.0.0.5"}
	if strings.Join(res.Hosts, ",") != strings.Join(want, ",") {
		t.Errorf("hosts = %v, want %v", res.Hosts, want)
	}

	// The token is minted into tokens.json with the host's name and '*'.
	if res.Token == nil || res.Token.Name != "laptop.example" || res.Token.Token == "" || len(res.Token.Projects) != 1 || res.Token.Projects[0] != "*" || res.Token.File != filepath.Join(opts.Dir, TokensFile) {
		t.Fatalf("token = %+v", res.Token)
	}
	if p, ok := auth.OpenTokenFile(res.Token.File).Lookup(res.Token.Token); !ok || p.AccountID != res.Token.AccountID || !auth.AllowProject(p, "github.com__acme__widgets") {
		t.Errorf("the minted token does not authenticate: %+v %v", p, ok)
	}

	compose, err := os.ReadFile(res.ComposeFile)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"name: clued\n", "  nginx:\n", "image: " + DefaultNginxImage, `"8443:443"`,
		"./nginx/clued.conf:/etc/nginx/conf.d/default.conf:ro", "./tls:/etc/nginx/tls:ro",
		"  clued-server:\n", "image: ghcr.io/robbiebyrd/clued-server:v9.9.9\n",
		`user: "1234:5678"`, `CLUED_SERVER_BEHIND_PROXY: "true"`, "CLUED_SERVER_CODE_STORE: mongo\n",
		"./tokens.json:/etc/clued/tokens.json:ro", "  mongo:\n", "image: " + DefaultMongoImage, "clued_mongo_data:/data/db",
		"generated by `mind-palace server init` on 2026-10-13",
	} {
		if !strings.Contains(string(compose), want) {
			t.Errorf("compose lacks %q:\n%s", want, compose)
		}
	}
	if strings.Contains(string(compose), "127.0.0.1:") {
		t.Error("with nginx the server must not be published itself")
	}
	// Every value is literal: Apple's compose plugin, among others, does not
	// interpolate ${VAR:-default}.
	if strings.Contains(string(compose), "${") {
		t.Errorf("compose interpolates variables:\n%s", compose)
	}
	stackDoc, err := os.ReadFile(filepath.Join(opts.Dir, StackFile))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{`"runtime": "compose"`, `"up": "` + res.Up + `"`, `"down": "` + res.Down + `"`, `"server_url": "https://localhost:8443"`} {
		if !strings.Contains(string(stackDoc), want) {
			t.Errorf("stack.json lacks %s:\n%s", want, stackDoc)
		}
	}
	nginx, err := os.ReadFile(filepath.Join(opts.Dir, NginxConf))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"listen 443 ssl;", "/etc/nginx/tls/cert.pem", "proxy_pass http://clued-server:8443;", "proxy_set_header Authorization $http_authorization;", "$connection_upgrade", "client_max_body_size 16m;"} {
		if !strings.Contains(string(nginx), want) {
			t.Errorf("nginx.conf lacks %q", want)
		}
	}
	cfg, err := os.ReadFile(filepath.Join(opts.Dir, ConfigFile))
	if err != nil || !strings.Contains(string(cfg), "kind: mongodb") || !strings.Contains(string(cfg), "uri: mongodb://mongo:27017") {
		t.Errorf("config = %s (%v)", cfg, err)
	}
	validateCompose(t, res.ComposeFile)
}

func TestInitIsIdempotentAndForceRenewsTheCertificates(t *testing.T) {
	opts := testOptions(t)
	first, err := Init(opts)
	if err != nil {
		t.Fatal(err)
	}
	caBefore := readPEMCert(t, first.CAFile)
	tokensBefore, _ := os.ReadFile(filepath.Join(opts.Dir, TokensFile))

	second, err := Init(opts)
	if err != nil {
		t.Fatal(err)
	}
	if second.TLS != TLSKept || second.Token != nil || len(second.Notes) != 1 || !strings.Contains(second.Notes[0], `token "laptop.example" already exists`) {
		t.Errorf("rerun = tls %q, token %+v, notes %v", second.TLS, second.Token, second.Notes)
	}
	if !readPEMCert(t, second.CAFile).Equal(caBefore) {
		t.Error("the rerun replaced the CA")
	}
	if tokensAfter, _ := os.ReadFile(filepath.Join(opts.Dir, TokensFile)); string(tokensAfter) != string(tokensBefore) {
		t.Error("the rerun changed tokens.json")
	}
	for _, kept := range []string{CAFile, CertFile, KeyFile, TokensFile} {
		found := false
		for _, k := range second.Kept {
			if k == filepath.Join(opts.Dir, kept) {
				found = true
			}
		}
		if !found {
			t.Errorf("%s not listed as kept: %v", kept, second.Kept)
		}
	}

	// Another name mints another token of the same account when asked.
	opts.TokenName = "desktop"
	opts.Account = first.Token.AccountID
	third, err := Init(opts)
	if err != nil {
		t.Fatal(err)
	}
	if third.Token == nil || third.Token.Name != "desktop" || third.Token.AccountID != first.Token.AccountID {
		t.Errorf("third token = %+v", third.Token)
	}

	// --force reissues the server certificate under the same CA, so a
	// machine that trusts the CA keeps trusting the server.
	certBefore := readPEMCert(t, filepath.Join(opts.Dir, CertFile))
	opts.Force = true
	opts.NoToken = true
	forced, err := Init(opts)
	if err != nil {
		t.Fatal(err)
	}
	if forced.TLS != TLSGenerated || forced.CA != CAKept || !readPEMCert(t, forced.CAFile).Equal(caBefore) || forced.Token != nil {
		t.Errorf("--force: tls %q, ca %q, CA replaced %v", forced.TLS, forced.CA, !readPEMCert(t, forced.CAFile).Equal(caBefore))
	}
	if readPEMCert(t, filepath.Join(opts.Dir, CertFile)).Equal(certBefore) {
		t.Error("--force did not reissue the server certificate")
	}
	if forced.CAFingerprint != Fingerprint(caBefore) {
		t.Errorf("fingerprint = %s", forced.CAFingerprint)
	}

	// A host the CA does not cover needs a new CA, and says so.
	opts.Hosts = []string{"clued.lan"}
	widened, err := Init(opts)
	if err != nil {
		t.Fatal(err)
	}
	if widened.CA != CAGenerated || readPEMCert(t, widened.CAFile).Equal(caBefore) || !strings.Contains(strings.Join(widened.Notes, " "), "the CA changed") {
		t.Errorf("a new host: ca %q, notes %v", widened.CA, widened.Notes)
	}

	// --new-ca replaces it on demand.
	caWidened := readPEMCert(t, widened.CAFile)
	opts.NewCA = true
	renewed, err := Init(opts)
	if err != nil {
		t.Fatal(err)
	}
	if renewed.CA != CAGenerated || readPEMCert(t, renewed.CAFile).Equal(caWidened) {
		t.Errorf("--new-ca kept the CA: %q", renewed.CA)
	}
}

func TestTheCAIsNameConstrainedToTheStacksHosts(t *testing.T) {
	opts := testOptions(t)
	res, err := Init(opts)
	if err != nil {
		t.Fatal(err)
	}
	ca := readPEMCert(t, res.CAFile)
	if !ca.PermittedDNSDomainsCritical || !slices.Contains(ca.PermittedDNSDomains, "localhost") || len(ca.PermittedIPRanges) != 3 {
		t.Fatalf("constraints = %v %v", ca.PermittedDNSDomains, ca.PermittedIPRanges)
	}
	roots := x509.NewCertPool()
	roots.AddCert(ca)
	leaf := readPEMCert(t, filepath.Join(opts.Dir, CertFile))
	for _, name := range []string{"localhost", "127.0.0.1", "laptop.example"} {
		if _, err := leaf.Verify(x509.VerifyOptions{Roots: roots, DNSName: name}); err != nil {
			t.Errorf("the server certificate does not verify for %s: %v", name, err)
		}
	}
	// A certificate for another name, signed with the stack's CA key, is
	// refused: trusting the CA trusts nothing but this server.
	authority, err := loadCA(opts.Dir)
	if err != nil {
		t.Fatal(err)
	}
	key, _ := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	der, err := x509.CreateCertificate(rand.Reader, &x509.Certificate{
		SerialNumber: big.NewInt(7), Subject: pkix.Name{CommonName: "bank"}, DNSNames: []string{"bank.example.com"},
		NotBefore: time.Now().Add(-time.Hour), NotAfter: time.Now().Add(time.Hour), ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}, authority.cert, &key.PublicKey, authority.key)
	if err != nil {
		t.Fatal(err)
	}
	other, _ := x509.ParseCertificate(der)
	if _, err := other.Verify(x509.VerifyOptions{Roots: roots, DNSName: "bank.example.com"}); err == nil {
		t.Error("the CA vouched for a name outside the stack")
	}
}

