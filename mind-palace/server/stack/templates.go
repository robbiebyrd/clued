// configYAML is the server's plan and story storage: MongoDB alone, which
// `server run` accepts (AllowNoFileStore) and namespaces per project.
func configYAML() string {
	return `# The clued server's plan and story storage, generated by ` + "`mind-palace server init`" + `.
# Plans and stories live in MongoDB alone and are namespaced per project
# (collection mp_<project>_plans, ...). The clients keep their own Markdown
# files under docs/plans and docs/stories and fan every write out to this
# store. Sessions are stored by CLUED_MONGO_URL / CLUED_DB_NAME instead.
storage:
  - name: mongo
    kind: mongodb
    options:
      uri: mongodb://mongo:27017
      database: mind_palace
      collection: mp_
`
}

// nginxConf is the front-end: TLS from tls/cert.pem and tls/key.pem, the
// Authorization header and WebSocket upgrades passed through unchanged,
// bodies up to the server's own 16 MiB cap and long reads for /ws.
func nginxConf() string {
	return `# nginx front-end for the clued server, generated by ` + "`mind-palace server init`" + `.
# Mounted at /etc/nginx/conf.d/default.conf; the certificate and key come
# from the stack's tls/ directory (generated, or supplied with --no-tls).
map $http_upgrade $connection_upgrade {
    default upgrade;
    ''      close;
}

server {
    listen 443 ssl;
    http2 on;
    server_name _;

    ssl_certificate     /etc/nginx/tls/cert.pem;
    ssl_certificate_key /etc/nginx/tls/key.pem;
    ssl_protocols       TLSv1.2 TLSv1.3;

    # The server caps request bodies at 16 MiB itself.
    client_max_body_size 16m;

    location /health {
        proxy_pass http://clued-server:8443/health;
        proxy_set_header Host $host;
    }

    location / {
        proxy_pass http://clued-server:8443;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header Authorization $http_authorization;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_read_timeout 3600s;
        proxy_send_timeout 3600s;
    }
}
`
}

// composeYAML renders the compose file for opts (defaults applied).
func composeYAML(opts Options) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("# The clued server stack, generated by `mind-palace server init` on %s.\n", opts.Now().UTC().Format("2006-01-02"))
	w("# Rerunning it regenerates this file, nginx/clued.conf and\n")
	w("# mind-palace.config.yaml; tls/ and tokens.json are kept (--force renews the\n")
	w("# certificates). See docs/server.md in the clued repository.\n#\n")
	w("#   docker compose -f %s up -d\n", opts.Dir+"/"+ComposeFile)
	if opts.Proxy == ProxyNginx {
		if opts.NoTLS {
			w("#   curl https://localhost:%d/health\n", opts.Port)
		} else {
			w("#   curl --cacert %s https://localhost:%d/health\n", opts.Dir+"/"+CAFile, opts.Port)
		}
	} else {
		w("#   curl http://127.0.0.1:%d/health\n", opts.Port)
	}
	w("#\n# CLUED_SERVER_IMAGE, CLUED_PUBLIC_PORT and CLUED_SERVER_USER override the\n")
	w("# image, the published port and the user without regenerating.\n")
	w("services:\n")

	if opts.Proxy == ProxyNginx {
		w("  nginx:\n")
		w("    # Terminates TLS with tls/cert.pem and tls/key.pem and forwards to the\n")
		w("    # clued server. Drop this service (`server init --proxy none`) to put\n")
		w("    # another terminator in front of the server instead.\n")
		w("    image: %s\n", opts.NginxImage)
		w("    container_name: clued-nginx\n")
		w("    restart: unless-stopped\n")
		w("    depends_on:\n      - clued-server\n")
		w("    ports:\n      - \"${CLUED_PUBLIC_PORT:-%d}:443\"\n", opts.Port)
		w("    volumes:\n")
		w("      - ./nginx/clued.conf:/etc/nginx/conf.d/default.conf:ro\n")
		w("      - ./tls:/etc/nginx/tls:ro\n\n")
	}

	w("  clued-server:\n")
	w("    image: ${CLUED_SERVER_IMAGE:-%s}\n", opts.ServerImage)
	w("    container_name: clued-server\n")
	w("    restart: unless-stopped\n")
	w("    # The token file is 0600 and owned by whoever minted it; the container\n")
	w("    # runs as that user so it can read it.\n")
	w("    user: \"${CLUED_SERVER_USER:-%s}\"\n", composeUser(opts))
	w("    depends_on:\n      mongo:\n        condition: service_healthy\n")
	w("    environment:\n")
	w("      CLUED_SERVER_ADDR: 0.0.0.0:8443\n")
	w("      CLUED_SERVER_TOKENS: /etc/clued/tokens.json\n")
	w("      MIND_PALACE_CONFIG: /etc/clued/mind-palace.config.yaml\n")
	w("      CLUED_MONGO_URL: mongodb://mongo:27017\n")
	w("      CLUED_DB_NAME: claude_sessions\n")
	if opts.Proxy == ProxyNginx {
		w("      # Plain HTTP inside the compose network only: nginx terminates TLS.\n")
	} else {
		w("      # Plain HTTP on loopback only: the terminator on this host (Caddy,\n")
		w("      # Traefik, nginx, an ingress) forwards to it. Never publish it off\n")
		w("      # loopback without TLS in front.\n")
	}
	w("      CLUED_SERVER_BEHIND_PROXY: \"true\"\n")
	if opts.Proxy == ProxyNone {
		w("    ports:\n      - \"127.0.0.1:${CLUED_PUBLIC_PORT:-%d}:8443\"\n", opts.Port)
	}
	w("    volumes:\n")
	w("      - ./tokens.json:/etc/clued/tokens.json:ro\n")
	w("      - ./mind-palace.config.yaml:/etc/clued/mind-palace.config.yaml:ro\n\n")

	w("  mongo:\n")
	w("    image: %s\n", opts.MongoImage)
	w("    container_name: clued-mongo\n")
	w("    restart: unless-stopped\n")
	w("    # Not published: only the server reaches it over the compose network.\n")
	w("    volumes:\n      - clued_mongo_data:/data/db\n")
	w("    healthcheck:\n")
	w("      test: echo 'db.runCommand(\"ping\").ok' | mongosh --port 27017 --quiet\n")
	w("      interval: 5s\n      timeout: 30s\n      start_period: 0s\n      start_interval: 1s\n      retries: 30\n\n")
	w("volumes:\n  clued_mongo_data:\n")
	return b.String()
}

// composeUser is the uid:gid the clued-server container runs as.
func composeUser(opts Options) string {
	if opts.UID < 0 || opts.GID < 0 {
		return "1000:1000"
	}
	return fmt.Sprintf("%d:%d", opts.UID, opts.GID)
}
