// periodFlags are the --day or --from/--to flags of report and digest.
type periodFlags struct {
	day, from, to string
}

func (p *periodFlags) add(c *cobra.Command) {
	f := c.Flags()
	f.StringVar(&p.day, "day", "", "one UTC day, YYYY-MM-DD (default: today)")
	f.StringVar(&p.from, "from", "", "first day of a range, YYYY-MM-DD (with --to)")
	f.StringVar(&p.to, "to", "", "last day of a range, YYYY-MM-DD (with --from)")
}

// period reads the flags: a day (today by default) or a range.
func (p *periodFlags) period(now func() time.Time) (digest.Period, error) {
	switch {
	case p.from != "" || p.to != "":
		if p.day != "" || p.from == "" || p.to == "" {
			return digest.Period{}, errors.New("give either --day, or both --from and --to")
		}
		return digest.Range(p.from, p.to)
	case p.day != "":
		return digest.Day(p.day)
	}
	return digest.Day(now().UTC().Format("2006-01-02"))
}

// sessionReportCmd is `session report`: the activity report of a day or a
// range of days, as Markdown or JSON.
func (a *App) sessionReportCmd() *cobra.Command {
	var pf periodFlags
	var opts digest.Options
	var include []string
	var format string
	c := &cobra.Command{
		Use:   "report [--day YYYY-MM-DD | --from d --to d] [--include kinds] [--format markdown|json] [--project-path re] [--git-origin re]",
		Short: "Render the activity report of a day or a range of days: one section per session, one row per activity",
		Args:  cobra.NoArgs,
	}
	c.RunE = func(cmd *cobra.Command, _ []string) error {
		if err := a.validated(checkRegex("--project-path", opts.ProjectPath), checkRegex("--git-origin", opts.GitOrigin)); err != nil {
			return err
		}
		if format != "markdown" && format != "json" {
			return a.sessionBadRequest("--format must be markdown or json")
		}
		p, err := pf.period(time.Now)
		if err != nil {
			return a.sessionBadRequest(err.Error())
		}
		opts.Kinds = splitKinds(include)
		defer a.closeSessionStore()
		store, err := a.sessionStore(cmd.Context())
		if err != nil {
			return a.sessionFail(err)
		}
		svc := a.digestService(store)
		rep, err := digest.Build(cmd.Context(), svc.Query, p, opts)
		if err != nil {
			return a.sessionFail(err)
		}
		if format == "json" {
			a.print(a.Stdout, map[string]any{"ok": true, "result": session.JSONTimes(rep)})
			return nil
		}
		fmt.Fprint(a.Stdout, rep.Markdown())
		if rep.Warning != "" {
			fmt.Fprintln(a.Stderr, "warning: "+rep.Warning)
		}
		return nil
	}
	pf.add(c)
	f := c.Flags()
	f.StringSliceVar(&include, "include", nil, "activity kinds to show, comma-separated (default user,response,bash,edit,thinking,task; also read, commit, tool, result, state, compaction, api_error, turn, other)")
	f.StringVar(&format, "format", "markdown", "markdown (the report) or json (the report's structure in the envelope)")
	f.StringVar(&opts.ProjectPath, "project-path", "", "only sessions whose project path matches this regular expression")
	f.StringVar(&opts.GitOrigin, "git-origin", "", "only sessions whose git origin matches this regular expression")
	return c
}

// sessionDigestCmd is `session digest`: the retro of a day or a range,
// generated by an engine and kept as a memory record of kind digest.
func (a *App) sessionDigestCmd() *cobra.Command {
	var pf periodFlags
	var opts digest.Options
	var include []string
	var model, engine, templateDir string
	var force, show bool
	c := &cobra.Command{
		Use:   "digest [--day YYYY-MM-DD | --from d --to d] [--engine claude|none] [--model m] [--force] [--show] [--include kinds] [--project-path re] [--git-origin re] [--template-dir d]",
		Short: "Write (or show) the first-person retro of a day or a range of days from the activity report",
		Long: `Builds the period's activity report (session report), renders the prompt
(templates/daily.md or templates/range.md, overridden by a file of the same
name under --template-dir, by default digest/ next to the config file) and
runs the engine: "claude" pipes the prompt to
"claude -p --no-session-persistence --output-format stream-json"; "none"
prints the report and the prompt for another tool and stores nothing. The
digest is stored as a memory record of kind "digest" (search_memory,
get_digest, the prime report's MEMORY section), once per finished period:
a past day is answered from the store unless --force, today is always
regenerated. A range digest is built from its days' digests, generating
the missing ones first. --show prints the stored digest and generates
nothing.`,
		Args: cobra.NoArgs,
	}
	c.RunE = func(cmd *cobra.Command, _ []string) error {
		if err := a.validated(checkRegex("--project-path", opts.ProjectPath), checkRegex("--git-origin", opts.GitOrigin)); err != nil {
			return err
		}
		if engine != "claude" && engine != "none" {
			return a.sessionBadRequest("--engine must be claude or none")
		}
		p, err := pf.period(time.Now)
		if err != nil {
			return a.sessionBadRequest(err.Error())
		}
		opts.Kinds = splitKinds(include)
		defer a.closeSessionStore()
		store, err := a.sessionStore(cmd.Context())
		if err != nil {
			return a.sessionFail(err)
		}
		svc := a.digestService(store)
		if templateDir != "" {
			svc.TemplateDir = templateDir
		}
		ctx := cmd.Context()
		switch {
		case show:
			d, err := svc.Cached(ctx, p)
			if err != nil {
				return a.sessionFail(err)
			}
			if d == nil {
				return a.fail(&service.Error{Kind: service.KindNotFound, Message: "no digest stored for " + p.String()})
			}
			a.print(a.Stdout, map[string]any{"ok": true, "result": session.JSONTimes(d)})
			return nil
		case engine == "none":
			prompt, rep, err := svc.Prompt(ctx, p, opts)
			if err != nil {
				return a.sessionFail(err)
			}
			if p.IsDay() {
				fmt.Fprint(a.Stdout, rep.Markdown())
				fmt.Fprint(a.Stdout, "\n---\n\n")
			}
			fmt.Fprintln(a.Stdout, prompt)
			if rep.Warning != "" {
				fmt.Fprintln(a.Stderr, "warning: "+rep.Warning)
			}
			return nil
		}
		d, err := svc.Generate(ctx, p, opts, digest.ClaudeEngine{}, model, force)
		if err != nil {
			if errors.Is(err, digest.ErrNoSessions) {
				return a.fail(&service.Error{Kind: service.KindNotFound, Message: err.Error()})
			}
			return a.sessionFail(err)
		}
		a.print(a.Stdout, map[string]any{"ok": true, "result": session.JSONTimes(d)})
		return nil
	}
	pf.add(c)
	f := c.Flags()
	f.StringVar(&engine, "engine", "claude", "claude (run the Claude Code CLI) or none (print the report and the prompt)")
	f.StringVar(&model, "model", "", "model the engine uses (its default when empty)")
	f.BoolVar(&force, "force", false, "regenerate a stored digest")
	f.BoolVar(&show, "show", false, "print the stored digest of the period and generate nothing")
	f.StringSliceVar(&include, "include", nil, "activity kinds the report shows, comma-separated (default user,response,bash,edit,thinking,task)")
	f.StringVar(&opts.ProjectPath, "project-path", "", "only sessions whose project path matches this regular expression")
	f.StringVar(&opts.GitOrigin, "git-origin", "", "only sessions whose git origin matches this regular expression")
	f.StringVar(&templateDir, "template-dir", "", "directory whose daily.md and range.md override the built-in prompts (default: digest/ next to the config file)")
	return c
}

// digestService builds the digest service over the store, with the
// account and the template override directory of the config.
func (a *App) digestService(store session.Store) *digest.Service {
	cfg := a.sessionConfig()
	account := session.AccountIDFor(cfg)
	return &digest.Service{
		Store:       store,
		AccountID:   account,
		Query:       &query.Service{Store: store, AccountID: account, Prices: cfg.ModelPrices},
		TemplateDir: filepath.Join(configDir(cfg), "digest"),
	}
}

// splitKinds reads the --include values, each possibly comma-separated.
func splitKinds(values []string) []string {
	var out []string
	for _, v := range values {
		for _, k := range strings.Split(v, ",") {
			if k = strings.TrimSpace(k); k != "" {
				out = append(out, k)
			}
		}
	}
	return out
}
